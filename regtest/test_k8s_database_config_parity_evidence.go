// k8sCPMount is one mount of the contract: where the container sees it and which directory of the claim it is.
type k8sCPMount struct{ Path, SubPath string }

var (
	k8sCPMountData = k8sCPMount{"/var/lib/mysql", "data"}
	k8sCPMountEtc  = k8sCPMount{"/etc/mysql", "etc/mysql"}
	k8sCPMountInit = k8sCPMount{"/docker-entrypoint-initdb.d", "init"}
)

// k8sCPContractMounts is what each container of the database Pod mounts from the claim, as OpenSVC does:
// the init container installs the configuration and the scripts (all three directories), the database sees
// its data and its configuration, the dbjobs sidecar sees the three.
var k8sCPContractMounts = map[string][]k8sCPMount{
	"init":     {k8sCPMountData, k8sCPMountEtc, k8sCPMountInit},
	"database": {k8sCPMountData, k8sCPMountEtc},
	"dbjobs":   {k8sCPMountData, k8sCPMountEtc, k8sCPMountInit},
}

// k8sCPLayoutVerdict says what the annotation of the data claim allows, with the same contract as the
// product's k8sPVCLayoutOf: a claim WITHOUT the annotation is a legacy claim and gets skip (nothing is
// changed, the test is not applicable: an older claim keeps the layout it was created with); the one known
// value is eligible; any other value, an empty one included, is fail (the product refuses to provision a
// database on a claim whose layout it does not know).
func k8sCPLayoutVerdict(annotations map[string]string) (skip, fail string) {
	v, ok := annotations[k8sCPLayoutAnnotation]
	switch {
	case !ok:
		return fmt.Sprintf("the data PVC has no %s annotation: it is a legacy claim, not a service-dirs-v1 one; nothing is asserted on it", k8sCPLayoutAnnotation), ""
	case v != k8sCPLayoutValue:
		return "", fmt.Sprintf("the data PVC carries %s=%q, expected %q: the product refuses to provision on a layout it does not know", k8sCPLayoutAnnotation, v, k8sCPLayoutValue)
	}
	return "", ""
}

// k8sCPMountProblems checks the volume mounts of the three containers of a database Pod (or of the Pod
// template of its Deployment) against the contract (k8sCPContractMounts), and that nothing mounts a .system
// directory or only conf.d (the legacy layout).
func k8sCPMountProblems(spec apiv1.PodSpec, server, claim string) []string {
	var problems []string
	volumes := map[string]string{} // volume name -> claim
	for _, v := range spec.Volumes {
		if v.PersistentVolumeClaim != nil {
			volumes[v.Name] = v.PersistentVolumeClaim.ClaimName
		}
	}
	find := func(list []apiv1.Container, name string) *apiv1.Container {
		for i := range list {
			if list[i].Name == name {
				return &list[i]
			}
		}
		return nil
	}
	for _, c := range []struct {
		role string
		ctr  *apiv1.Container
		name string
	}{
		{"init", find(spec.InitContainers, server+"-init"), server + "-init"},
		{"database", find(spec.Containers, server), server},
		{"dbjobs", find(spec.Containers, server+"-dbjobs"), server + "-dbjobs"},
	} {
		if c.ctr == nil {
			problems = append(problems, fmt.Sprintf("the %s container %s is not in the Pod spec", c.role, c.name))
			continue
		}
		for _, want := range k8sCPContractMounts[c.role] {
			var found []apiv1.VolumeMount
			for _, m := range c.ctr.VolumeMounts {
				if m.MountPath == want.Path {
					found = append(found, m)
				}
			}
			switch {
			case len(found) == 0:
				problems = append(problems, fmt.Sprintf("the %s container does not mount %s", c.role, want.Path))
			case len(found) > 1:
				problems = append(problems, fmt.Sprintf("the %s container mounts %s %d times", c.role, want.Path, len(found)))
			case found[0].SubPath != want.SubPath:
				problems = append(problems, fmt.Sprintf("the %s container mounts %s from subPath %q, expected %q", c.role, want.Path, found[0].SubPath, want.SubPath))
			case volumes[found[0].Name] != claim:
				problems = append(problems, fmt.Sprintf("the %s container mounts %s from volume %q, which is not the data claim %s", c.role, want.Path, found[0].Name, claim))
			}
		}
		for _, m := range c.ctr.VolumeMounts {
			if m.MountPath == "/etc/mysql/conf.d" || strings.HasPrefix(m.SubPath, ".system") {
				problems = append(problems, fmt.Sprintf("the %s container has a legacy mount: %s from subPath %q", c.role, m.MountPath, m.SubPath))
			}
		}
	}
	return problems
}

