// k8sCPTree is the archive replication-manager serves to the init container: the files and the symbolic
// links of the tree, by their path in the archive (etc/mysql/..., init/...).
type k8sCPTree struct {
	Files map[string][]byte
	Links map[string]string // path -> link target as written
}

// k8sCPReadArchive reads the config.tar.gz of a server. The read is bounded: entries, bytes of one file and
// bytes in all.
func k8sCPReadArchive(data []byte) (*k8sCPTree, error) {
	zr, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return nil, fmt.Errorf("the archive is not gzip: %w", err)
	}
	defer zr.Close()
	tr := tar.NewReader(zr)
	t := &k8sCPTree{Files: map[string][]byte{}, Links: map[string]string{}}
	entries, total := 0, 0
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("the archive is not a tar: %w", err)
		}
		if entries++; entries > k8sCPMaxEntries {
			return nil, fmt.Errorf("the archive has more than %d entries", k8sCPMaxEntries)
		}
		name := path.Clean(strings.TrimPrefix(h.Name, "./"))
		switch h.Typeflag {
		case tar.TypeSymlink:
			t.Links[name] = h.Linkname
		case tar.TypeReg:
			if h.Size > k8sCPMaxFileBytes {
				return nil, fmt.Errorf("%s is larger than %d bytes", name, k8sCPMaxFileBytes)
			}
			body, err := io.ReadAll(io.LimitReader(tr, k8sCPMaxFileBytes+1))
			if err != nil {
				return nil, fmt.Errorf("cannot read %s: %w", name, err)
			}
			if total += len(body); total > k8sCPMaxTotalBytes {
				return nil, fmt.Errorf("the archive holds more than %d bytes", k8sCPMaxTotalBytes)
			}
			t.Files[name] = body
		}
	}
	if len(t.Files) == 0 {
		return nil, errors.New("the archive holds no file")
	}
	return t, nil
}

// Resolve returns the content of a file of the tree, following symbolic links the way the volume does.
func (t *k8sCPTree) Resolve(name string) ([]byte, bool) {
	for depth := 0; depth < 8; depth++ {
		if b, ok := t.Files[name]; ok {
			return b, true
		}
		target, ok := t.Links[name]
		if !ok {
			return nil, false
		}
		if path.IsAbs(target) {
			name = path.Clean(strings.TrimPrefix(target, "/"))
		} else {
			name = path.Clean(path.Join(path.Dir(name), target))
		}
	}
	return nil, false
}

// Names are the files and links of the tree under a directory prefix ("etc/mysql/"), sorted.
func (t *k8sCPTree) Names(prefix string) []string {
	var out []string
	for n := range t.Files {
		if strings.HasPrefix(n, prefix) {
			out = append(out, n)
		}
	}
	for n := range t.Links {
		if strings.HasPrefix(n, prefix) {
			out = append(out, n)
		}
	}
	sort.Strings(out)
	return out
}

// k8sCPNormHash is the hash of a file as the observation script computes it: without the "# Generated by
// ... on <time>" line, which the generator stamps with the time of the generation, and with a newline after
// the last line, which grep adds when the file lacks one.
func k8sCPNormHash(content []byte) string {
	h := sha256.New()
	for _, line := range bytes.SplitAfter(content, []byte("\n")) {
		if len(line) == 0 || bytes.HasPrefix(line, []byte(k8sCPGeneratedLine)) {
			continue
		}
		h.Write(line)
		if line[len(line)-1] != '\n' {
			h.Write([]byte("\n"))
		}
	}
	return hex.EncodeToString(h.Sum(nil))
}

// k8sCPVolatile returns the paths whose content (without the generation stamp) differs between two
// generations of the same tree, or that exist in only one of them, and everything under custom.d: they are
// checked for presence, not for content.
func k8sCPVolatile(a, b *k8sCPTree) map[string]bool {
	out := map[string]bool{}
	// custom.d carries the preserved and delta settings, which replication-manager changes at runtime
	// from the state of the database: it is present, never compared by content
	for _, t := range []*k8sCPTree{a, b} {
		for _, n := range t.Names("etc/mysql/custom.d/") {
			out[n] = true
		}
	}
	for _, n := range a.Names("") {
		ca, _ := a.Resolve(n)
		cb, ok := b.Resolve(n)
		if !ok || k8sCPNormHash(ca) != k8sCPNormHash(cb) {
			out[n] = true
		}
	}
	for _, n := range b.Names("") {
		if _, ok := a.Resolve(n); !ok {
			out[n] = true
		}
	}
	return out
}

