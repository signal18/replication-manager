// k8sCPOption is the last value an applicable option group gives an option, and where it comes from.
type k8sCPOption struct {
	Value    string
	HasValue bool
	File     string
}

type k8sCPEntry struct {
	Section, Key, Value string
	HasValue            bool
	Include             string // "!includedir <dir>" or "!include <file>", the directive's argument
	IncludeDir          bool
}

func k8sCPNormKey(k string) string {
	k = strings.ToLower(strings.TrimSpace(k))
	k = strings.ReplaceAll(k, "-", "_")
	return strings.TrimPrefix(k, "loose_")
}

// k8sCPParseCnf parses an option file: groups, options with or without a value, the include directives.
// Quotes around a value are removed; whole-line comments are skipped.
func k8sCPParseCnf(text string) []k8sCPEntry {
	var out []k8sCPEntry
	section := ""
	for _, raw := range strings.Split(text, "\n") {
		line := strings.TrimSpace(raw)
		switch {
		case line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";"):
			continue
		case strings.HasPrefix(line, "!includedir"):
			out = append(out, k8sCPEntry{Include: strings.TrimSpace(strings.TrimPrefix(line, "!includedir")), IncludeDir: true})
		case strings.HasPrefix(line, "!include"):
			out = append(out, k8sCPEntry{Include: strings.TrimSpace(strings.TrimPrefix(line, "!include"))})
		case strings.HasPrefix(line, "[") && strings.Contains(line, "]"):
			section = strings.ToLower(strings.TrimSpace(line[1:strings.Index(line, "]")]))
		default:
			e := k8sCPEntry{Section: section}
			if i := strings.Index(line, "="); i >= 0 {
				e.Key = k8sCPNormKey(line[:i])
				e.Value = strings.Trim(strings.TrimSpace(line[i+1:]), `"'`)
				e.HasValue = true
			} else {
				e.Key = k8sCPNormKey(line)
			}
			out = append(out, e)
		}
	}
	return out
}

// k8sCPSectionApplies says whether a server of that flavour and version reads an option group: the groups
// of its server, and the version-specific ones for its exact major.minor.
func k8sCPSectionApplies(section string, maria bool, major, minor int) bool {
	suffix := fmt.Sprintf("-%d.%d", major, minor)
	if maria {
		for _, g := range []string{"mysqld", "server", "mariadb", "mariadbd"} {
			if section == g || section == g+suffix {
				return true
			}
		}
		return false
	}
	return section == "mysqld" || section == "mysqld"+suffix
}

// k8sCPEffective reads etc/mysql/my.cnf and what it includes, in order, like the server does, and returns
// the last value of each option from the groups the server reads. The include directives name directories
// of the volume as the server sees them (/etc/mysql/...).
func k8sCPEffective(t *k8sCPTree, maria bool, major, minor int) (map[string]k8sCPOption, error) {
	out := map[string]k8sCPOption{}
	var walk func(file string, depth int) error
	walk = func(file string, depth int) error {
		if depth > 4 {
			return fmt.Errorf("option files include each other too deeply at %s", file)
		}
		body, ok := t.Resolve(file)
		if !ok {
			return fmt.Errorf("the option file %s is not in the generated tree", file)
		}
		for _, e := range k8sCPParseCnf(string(body)) {
			switch {
			case e.Include != "":
				rel := strings.TrimPrefix(e.Include, "/")
				if !strings.HasPrefix(e.Include, k8sCPEtcMysqlPrefix) {
					continue // outside the generated tree (the image's own files)
				}
				if e.IncludeDir {
					for _, n := range t.Names(strings.TrimSuffix(rel, "/") + "/") {
						if strings.HasSuffix(n, ".cnf") && !strings.Contains(strings.TrimPrefix(n, strings.TrimSuffix(rel, "/")+"/"), "/") {
							if err := walk(n, depth+1); err != nil {
								return err
							}
						}
					}
				} else if err := walk(rel, depth+1); err != nil {
					return err
				}
			case k8sCPSectionApplies(e.Section, maria, major, minor):
				out[e.Key] = k8sCPOption{Value: e.Value, HasValue: e.HasValue, File: file}
			}
		}
		return nil
	}
	if err := walk("etc/mysql/my.cnf", 0); err != nil {
		return nil, err
	}
	return out, nil
}

