// k8sCPMariaGTIDList reads a MariaDB GTID list (domain-server-seq,...) as the highest sequence per domain.
func k8sCPMariaGTIDList(s string) (map[string]uint64, error) {
	out := map[string]uint64{}
	for _, g := range strings.Split(strings.TrimSpace(s), ",") {
		g = strings.TrimSpace(g)
		if g == "" {
			continue
		}
		p := strings.Split(g, "-")
		if len(p) != 3 {
			return nil, fmt.Errorf("%q is not a MariaDB GTID", g)
		}
		seq, err := strconv.ParseUint(p[2], 10, 64)
		if err != nil {
			return nil, fmt.Errorf("%q is not a MariaDB GTID: %w", g, err)
		}
		if seq > out[p[0]] {
			out[p[0]] = seq
		}
	}
	return out, nil
}

// k8sCPMariaGTIDNotBehind is true when, in every replication domain of before, after is at the same
// sequence or later: the position of a MariaDB server did not go back. It is a containment check, not an
// equality: the probe writes of the test advance the position.
func k8sCPMariaGTIDNotBehind(before, after string) (bool, string, error) {
	b, err := k8sCPMariaGTIDList(before)
	if err != nil {
		return false, "", err
	}
	a, err := k8sCPMariaGTIDList(after)
	if err != nil {
		return false, "", err
	}
	for d, seq := range b {
		if a[d] < seq {
			return false, fmt.Sprintf("domain %s went from sequence %d back to %d", d, seq, a[d]), nil
		}
	}
	return true, "", nil
}

// k8sCPGTIDHasServer is true when some GTID of a MariaDB list was written by that server id.
func k8sCPGTIDHasServer(gtid, serverID string) bool {
	for _, g := range strings.Split(gtid, ",") {
		if p := strings.Split(strings.TrimSpace(g), "-"); len(p) == 3 && p[1] == serverID {
			return true
		}
	}
	return false
}

