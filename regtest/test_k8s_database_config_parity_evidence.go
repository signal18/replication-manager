// k8sCPRequired are the checks every engine must pass: a required check that did not run is not a PASS.
var k8sCPRequired = []string{"C0", "C1", "S1", "C2", "C3", "C4", "C5", "C6", "C7", "C8"}

// k8sCPMissingChecks returns the required checks that are not in passed.
func k8sCPMissingChecks(passed []string) []string {
	have := map[string]bool{}
	for _, p := range passed {
		have[p] = true
	}
	var out []string
	for _, c := range k8sCPRequired {
		if !have[c] {
			out = append(out, c)
		}
	}
	return out
}
