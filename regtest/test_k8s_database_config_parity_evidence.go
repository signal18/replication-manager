type k8sCPKind int

const (
	k8sCPInt k8sCPKind = iota
	k8sCPBool
	k8sCPPath
	k8sCPStr
)

// k8sCPSpec is one option the test follows from the generated tree to the running server.
type k8sCPSpec struct {
	Option    string // normalised option name in the generated files
	Var       string // global variable holding its value ("" = the option's own name)
	OriginVar string // variable whose origin is checked ("" = the option's own name)
	Kind      k8sCPKind
	Maria     bool // MariaDB reads it
	MySQL     bool // MySQL and Percona read it
	NoOrigin  bool // the server reports no option-file origin for it (log_bin is derived); the value is checked
	Required  bool // the generated tree must carry it: its absence is not a pass
	GTIDTag   bool // required only on MySQL and Percona that run with the mysqlgtid tag (gtid-mode)
}

var k8sCPSpecs = []k8sCPSpec{
	{Option: "server_id", Kind: k8sCPInt, Maria: true, MySQL: true, Required: true},
	{Option: "max_connections", Kind: k8sCPInt, Maria: true, MySQL: true, Required: true},
	// log_bin names the binary log prefix; the server reports it as log_bin_basename, and log_bin is ON.
	// Both are derived, read-only variables without an option-file origin: the proof that the option file was
	// read is the prefix, which is not the default one, and log_bin ON.
	{Option: "log_bin", Var: "log_bin_basename", Kind: k8sCPPath, NoOrigin: true, Maria: true, MySQL: true, Required: true},
	{Option: "innodb_data_home_dir", Kind: k8sCPPath, Maria: true, MySQL: true, Required: true},
	{Option: "innodb_log_group_home_dir", Kind: k8sCPPath, Maria: true, MySQL: true, Required: true},
	{Option: "innodb_undo_directory", Kind: k8sCPPath, Maria: true, MySQL: true},
	{Option: "binlog_format", Kind: k8sCPStr, Maria: true, MySQL: true},
	{Option: "gtid_mode", Kind: k8sCPStr, MySQL: true, GTIDTag: true},
	{Option: "enforce_gtid_consistency", Kind: k8sCPBool, MySQL: true, GTIDTag: true},
	{Option: "gtid_strict_mode", Kind: k8sCPBool, Maria: true},
}

// k8sCPEnv is what decides which options apply.
type k8sCPEnv struct {
	Maria   bool
	GTIDTag bool // the cluster runs with the mysqlgtid tag
}

func (s k8sCPSpec) valueVar() string {
	if s.Var != "" {
		return s.Var
	}
	return s.Option
}

func (s k8sCPSpec) originVar() string {
	if s.OriginVar != "" {
		return s.OriginVar
	}
	return s.Option
}

// k8sCPApplicable returns the specs the engine reads.
func k8sCPApplicable(env k8sCPEnv) []k8sCPSpec {
	var out []k8sCPSpec
	for _, s := range k8sCPSpecs {
		if (env.Maria && s.Maria) || (!env.Maria && s.MySQL) {
			out = append(out, s)
		}
	}
	return out
}

// k8sCPVariableNames are the variables to read from the server for the applicable specs.
func k8sCPVariableNames(env k8sCPEnv) []string {
	seen := map[string]bool{"datadir": true, "log_bin": true}
	for _, s := range k8sCPApplicable(env) {
		seen[s.valueVar()] = true
		if !s.NoOrigin {
			seen[s.originVar()] = true
		}
	}
	var out []string
	for n := range seen {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

func k8sCPNormValue(kind k8sCPKind, v string) string {
	v = strings.TrimSpace(v)
	switch kind {
	case k8sCPInt:
		if n, err := strconv.ParseInt(v, 10, 64); err == nil {
			return strconv.FormatInt(n, 10)
		}
		return v
	case k8sCPBool:
		switch strings.ToUpper(v) {
		case "ON", "1", "TRUE", "YES":
			return "ON"
		case "OFF", "0", "FALSE", "NO":
			return "OFF"
		}
		return strings.ToUpper(v)
	case k8sCPPath:
		v = strings.Trim(v, `"'`)
		if len(v) > 1 {
			v = strings.TrimRight(v, "/")
		}
		return v
	}
	return strings.ToUpper(v)
}

// k8sCPFinding is one thing found against the guarantee, with its class.
type k8sCPFinding struct {
	Class  k8sSWClass
	Detail string
}

// k8sCPRow is one line of the comparison, for the log: names and non-secret settings only.
type k8sCPRow struct {
	Option, Expected, Live, Origin, Path string
}

// k8sCPEvaluate compares what the generated tree says with what the running server reports:
//   - an option the tree does not carry, although it is required, is INCONCLUSIVE (nothing to compare with);
//   - the value the server reports must be the generated one;
//   - the server must report that it got the value from an option file under /etc/mysql: a matching value
//     with another origin (compiled, command line) is no proof that the generated tree was loaded; a value
//     changed at runtime (DYNAMIC) is INCONCLUSIVE.
//
// log_bin has no value to compare when the option carries none: only the origin and log_bin = ON are
// checked then.
func k8sCPEvaluate(env k8sCPEnv, eff map[string]k8sCPOption, live map[string]dbhelper.VariableOrigin) (rows []k8sCPRow, findings []k8sCPFinding) {
	add := func(c k8sSWClass, format string, args ...interface{}) {
		findings = append(findings, k8sCPFinding{c, fmt.Sprintf(format, args...)})
	}
	for _, s := range k8sCPApplicable(env) {
		opt, have := eff[s.Option]
		required := s.Required || (s.GTIDTag && !env.Maria && env.GTIDTag)
		if !have {
			if required {
				add(k8sSWInconclusive, "the generated configuration carries no %s: there is nothing to compare the server with", s.Option)
			}
			continue
		}
		row := k8sCPRow{Option: s.Option, Expected: opt.Value}
		vv, vok := live[strings.ToUpper(s.valueVar())]
		ov, ook := live[strings.ToUpper(s.originVar())]
		if s.NoOrigin {
			ook = true
		}
		if !vok || !ook {
			add(k8sSWProduct, "the server does not report %s: it does not know the option the generated configuration sets", s.valueVar())
			rows = append(rows, row)
			continue
		}
		row.Live, row.Origin, row.Path = vv.Value, ov.Origin, ov.Path
		rows = append(rows, row)
		if opt.HasValue && opt.Value != "" {
			if want, got := k8sCPNormValue(s.Kind, opt.Value), k8sCPNormValue(s.Kind, vv.Value); want != got {
				add(k8sSWProduct, "%s: the generated configuration (%s) sets %q, the server reports %q", s.Option, opt.File, want, got)
				continue
			}
		}
		if s.Option == "log_bin" {
			if lb, ok := live["LOG_BIN"]; !ok || k8sCPNormValue(k8sCPBool, lb.Value) != "ON" {
				add(k8sSWProduct, "binary logging is not ON although the generated configuration sets log_bin")
			}
		}
		if s.NoOrigin {
			continue
		}
		switch {
		case ov.Origin == "CONFIG" && strings.HasPrefix(ov.Path, k8sCPEtcMysqlPrefix):
		case ov.Origin == "DYNAMIC":
			add(k8sSWInconclusive, "%s was changed at runtime (origin DYNAMIC): its origin cannot show what the generated configuration did", s.originVar())
		default:
			add(k8sSWProduct, "%s has the generated value but the server got it from origin %q path %q, not from an option file under %s: the generated configuration was not what set it", s.originVar(), ov.Origin, ov.Path, k8sCPEtcMysqlPrefix)
		}
	}
	// the data directory is the contract's, whatever the options say
	if dv, ok := live["DATADIR"]; !ok {
		add(k8sSWProduct, "the server does not report its datadir")
	} else if k8sCPNormValue(k8sCPPath, dv.Value) != "/var/lib/mysql" {
		add(k8sSWProduct, "the server's datadir is %q, expected /var/lib/mysql (the data directory of the claim)", dv.Value)
	}
	return rows, findings
}

// k8sCPOriginSnapshot is what must not change when the database restarts: the value and origin of every
// option the specs follow.
func k8sCPOriginSnapshot(rows []k8sCPRow) map[string]string {
	out := map[string]string{}
	for _, r := range rows {
		out[r.Option] = r.Live + "|" + r.Origin + "|" + r.Path
	}
	return out
}

// k8sCPSnapshotDiff names the options whose value or origin differ between two snapshots.
func k8sCPSnapshotDiff(before, after map[string]string) []string {
	var out []string
	for k, b := range before {
		if a, ok := after[k]; !ok {
			out = append(out, k+" (gone)")
		} else if a != b {
			out = append(out, k)
		}
	}
	for k := range after {
		if _, ok := before[k]; !ok {
			out = append(out, k+" (new)")
		}
	}
	sort.Strings(out)
	return out
}

