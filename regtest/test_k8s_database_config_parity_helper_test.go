type cpFile struct{ name, body, link string }

func cpArchive(t *testing.T, files []cpFile) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(zw)
	for _, f := range files {
		h := &tar.Header{Name: f.name, Mode: 0644}
		if f.link != "" {
			h.Typeflag, h.Linkname = tar.TypeSymlink, f.link
		} else {
			h.Typeflag, h.Size = tar.TypeReg, int64(len(f.body))
		}
		if err := tw.WriteHeader(h); err != nil {
			t.Fatal(err)
		}
		if f.link == "" {
			if _, err := tw.Write([]byte(f.body)); err != nil {
				t.Fatal(err)
			}
		}
	}
	tw.Close()
	zw.Close()
	return buf.Bytes()
}

