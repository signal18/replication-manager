func TestK8SCPArchiveAndLinks(t *testing.T) {
	tree := cpTree(t, cpFiles("t1"))
	if b, ok := tree.Resolve("etc/mysql/conf.d/01_default_network.cnf"); !ok || !strings.Contains(string(b), "max_connections") {
		t.Fatalf("a conf.d link does not resolve to its fragment: %v %q", ok, b)
	}
	if _, ok := tree.Resolve("etc/mysql/conf.d/nope.cnf"); ok {
		t.Error("an unknown name resolved")
	}
	loop := cpTree(t, []cpFile{{name: "a", link: "b"}, {name: "b", link: "a"}, {name: "c", body: "x"}})
	if _, ok := loop.Resolve("a"); ok {
		t.Error("a link loop must not resolve")
	}
	if _, err := k8sCPReadArchive([]byte("not gzip")); err == nil {
		t.Error("garbage is not an archive")
	}
	if _, err := k8sCPReadArchive(cpArchive(t, nil)); err == nil {
		t.Error("an archive without a file is an error")
	}
	var many []cpFile
	for i := 0; i <= k8sCPMaxEntries; i++ {
		many = append(many, cpFile{name: fmt.Sprintf("f%d", i), body: "x"})
	}
	if _, err := k8sCPReadArchive(cpArchive(t, many)); err == nil {
		t.Error("the number of entries is bounded")
	}
	if _, err := k8sCPReadArchive(cpArchive(t, []cpFile{{name: "big", body: strings.Repeat("a", k8sCPMaxFileBytes+1)}})); err == nil {
		t.Error("the size of a file is bounded")
	}
}

func TestK8SCPNormHashMatchesGrepOnAFileWithoutTrailingNewline(t *testing.T) {
	if k8sCPNormHash([]byte("[mysqld]\na=1")) != k8sCPNormHash([]byte("[mysqld]\na=1\n")) {
		t.Error("grep adds the newline the file lacks: the hash must not tell the two apart")
	}
	if k8sCPNormHash([]byte("# Generated by x on y\n")) != k8sCPNormHash(nil) {
		t.Error("a file holding only the stamp hashes as an empty file")
	}
	if k8sCPNormHash([]byte("a\n\nb")) == k8sCPNormHash([]byte("a\nb")) {
		t.Error("an empty line is content")
	}
}

func TestK8SCPNormHashIgnoresTheStamp(t *testing.T) {
	a := cpTree(t, cpFiles("2026-11-17T01:00:00Z"))
	b := cpTree(t, cpFiles("2026-11-17T01:00:09Z"))
	ca, _ := a.Resolve("etc/mysql/my.cnf")
	cb, _ := b.Resolve("etc/mysql/my.cnf")
	if k8sCPNormHash(ca) != k8sCPNormHash(cb) {
		t.Error("the generation stamp must not change the hash")
	}
	if k8sCPNormHash([]byte("[mysqld]\na=1\n")) == k8sCPNormHash([]byte("[mysqld]\na=2\n")) {
		t.Error("a content change must change the hash")
	}
	for n := range k8sCPVolatile(a, b) {
		if !strings.HasPrefix(n, "etc/mysql/custom.d/") {
			t.Errorf("only the stamp differs, so only custom.d is volatile: %s", n)
		}
	}
	// everything under custom.d is volatile: preserved and delta settings change at runtime
	if v := k8sCPVolatile(a, b); !v["etc/mysql/custom.d/03_agreed.cnf"] {
		t.Errorf("custom.d is checked for presence only: %v", v)
	}
	files := cpFiles("t")
	files[2].body = "[mysqld]\nmax_connections = 5\n"
	if v := k8sCPVolatile(a, cpTree(t, files)); !v["etc/mysql/replication-manager.d/default_network.cnf"] || !v["etc/mysql/conf.d/01_default_network.cnf"] {
		t.Errorf("a file whose content differs between generations is volatile, with its link: %v", v)
	}
}

func TestK8SCPEffectiveOptions(t *testing.T) {
	tree := cpTree(t, cpFiles("t"))
	eff, err := k8sCPEffective(tree, false, 8, 4)
	if err != nil {
		t.Fatal(err)
	}
	for k, want := range map[string]string{"server_id": "39645580", "max_connections": "1000", "log_bin": "/var/lib/mysql/.system/repl/binlog", "gtid_mode": "ON", "innodb_log_group_home_dir": "/var/lib/mysql/.system/innodb/redo/"} {
		if got := eff[k].Value; got != want {
			t.Errorf("%s=%q, want %q", k, got, want)
		}
	}
	if _, has := eff["innodb_undo_directory"]; has {
		t.Error("[mysqld-8.0] is not read by 8.4")
	}
	if eff["server_id"].File != "etc/mysql/conf.d/01_default_replication.cnf" {
		t.Errorf("the option names the path the server includes it from (the conf.d link, which is what the server reports): %q", eff["server_id"].File)
	}
	if eff, _ = k8sCPEffective(tree, false, 8, 0); eff["innodb_undo_directory"].Value != "./" {
		t.Errorf("[mysqld-8.0] with loose_ is read by 8.0: %+v", eff["innodb_undo_directory"])
	}
	// last value wins, in include order: custom.d after conf.d
	files := append(cpFiles("t"), cpFile{name: "etc/mysql/custom.d/04_override.cnf", body: "[mariadb]\nmax_connections=77\n[mysql]\nmax_connections=1\n"})
	if eff, _ = k8sCPEffective(cpTree(t, files), true, 11, 8); eff["max_connections"].Value != "77" {
		t.Errorf("custom.d is read after conf.d and [mariadb] applies to MariaDB: %+v", eff["max_connections"])
	}
	if eff, _ = k8sCPEffective(cpTree(t, files), false, 8, 4); eff["max_connections"].Value != "1000" {
		t.Errorf("[mariadb] and [mysql] do not apply to a MySQL server: %+v", eff["max_connections"])
	}
	if _, err := k8sCPEffective(cpTree(t, []cpFile{{name: "etc/mysql/other.cnf", body: "x"}}), true, 11, 8); err == nil {
		t.Error("a tree without my.cnf is an error, not an empty configuration")
	}
}

