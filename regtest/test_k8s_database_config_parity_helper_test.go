func cpClasses(f []k8sCPFinding) string {
	var out []string
	for _, x := range f {
		out = append(out, string(x.Class)+":"+x.Detail)
	}
	return strings.Join(out, " | ")
}

func TestK8SCPEvaluate(t *testing.T) {
	env := k8sCPEnv{GTIDTag: true}
	eff := cpEffective(t, false)
	rows, f := k8sCPEvaluate(env, eff, cpLive(false))
	if len(f) != 0 || len(rows) < 6 {
		t.Fatalf("a matching server: %d rows, findings %s", len(rows), cpClasses(f))
	}
	mutateLive := func(name string, f func(v *dbhelper.VariableOrigin)) map[string]dbhelper.VariableOrigin {
		l := cpLive(false)
		v := l[name]
		f(&v)
		l[name] = v
		return l
	}
	for name, c := range map[string]struct {
		live  map[string]dbhelper.VariableOrigin
		class k8sSWClass
		want  string
	}{
		"a different value":                   {mutateLive("MAX_CONNECTIONS", func(v *dbhelper.VariableOrigin) { v.Value = "151" }), k8sSWProduct, "reports \"151\""},
		"the value from the compiled default": {mutateLive("MAX_CONNECTIONS", func(v *dbhelper.VariableOrigin) { v.Origin, v.Path = "COMPILED", "" }), k8sSWProduct, "not from an option file"},
		"the value from the command line":     {mutateLive("SERVER_ID", func(v *dbhelper.VariableOrigin) { v.Origin = "COMMAND-LINE" }), k8sSWProduct, "COMMAND-LINE"},
		"an option file outside /etc/mysql":   {mutateLive("SERVER_ID", func(v *dbhelper.VariableOrigin) { v.Path = "/etc/my.cnf" }), k8sSWProduct, "/etc/my.cnf"},
		"a runtime change":                    {mutateLive("MAX_CONNECTIONS", func(v *dbhelper.VariableOrigin) { v.Origin = "DYNAMIC" }), k8sSWInconclusive, "DYNAMIC"},
		"binary logging off":                  {mutateLive("LOG_BIN", func(v *dbhelper.VariableOrigin) { v.Value = "OFF" }), k8sSWProduct, "binary logging is not ON"},
		"gtid_mode off":                       {mutateLive("GTID_MODE", func(v *dbhelper.VariableOrigin) { v.Value = "OFF" }), k8sSWProduct, "gtid_mode"},
		"a wrong binlog prefix":               {mutateLive("LOG_BIN_BASENAME", func(v *dbhelper.VariableOrigin) { v.Value = "/var/lib/mysql/binlog" }), k8sSWProduct, "log_bin"},
	} {
		_, f := k8sCPEvaluate(env, eff, c.live)
		if len(f) == 0 || !strings.Contains(cpClasses(f), string(c.class)+":") || !strings.Contains(cpClasses(f), c.want) {
			t.Errorf("%s: findings %q, want class %s containing %q", name, cpClasses(f), c.class, c.want)
		}
	}
	// log_bin is derived: it has no option-file origin, and the prefix with log_bin ON is the proof
	live := cpLive(false)
	lb := live["LOG_BIN"]
	lb.Origin, lb.Path = "COMPILED", ""
	live["LOG_BIN"] = lb
	bb := live["LOG_BIN_BASENAME"]
	bb.Origin, bb.Path = "COMPILED", ""
	live["LOG_BIN_BASENAME"] = bb
	if _, f := k8sCPEvaluate(env, eff, live); len(f) != 0 {
		t.Errorf("log_bin and log_bin_basename have no option-file origin by nature: %s", cpClasses(f))
	}
	// a variable the server does not know
	live = cpLive(false)
	delete(live, "INNODB_DATA_HOME_DIR")
	if _, f := k8sCPEvaluate(env, eff, live); !strings.Contains(cpClasses(f), "does not know the option") {
		t.Errorf("an unknown variable: %s", cpClasses(f))
	}
	// the data directory is the contract's
	live = cpLive(false)
	live["DATADIR"] = dbhelper.VariableOrigin{Name: "DATADIR", Value: "/var/lib/mysql/data/", Origin: "CONFIG"}
	if _, f := k8sCPEvaluate(env, eff, live); !strings.Contains(cpClasses(f), "datadir") {
		t.Errorf("a wrong datadir: %s", cpClasses(f))
	}
}

func TestK8SCPEvaluateRequiredOptionsAndEngines(t *testing.T) {
	// a required option missing from the generated tree is not a pass: there is nothing to compare with
	eff := cpEffective(t, false)
	delete(eff, "max_connections")
	if _, f := k8sCPEvaluate(k8sCPEnv{GTIDTag: true}, eff, cpLive(false)); !strings.Contains(cpClasses(f), "INCONCLUSIVE:the generated configuration carries no max_connections") {
		t.Errorf("a required option the tree lacks: %s", cpClasses(f))
	}
	// gtid-mode is required only with the tag on MySQL and Percona
	eff = cpEffective(t, false)
	delete(eff, "gtid_mode")
	if _, f := k8sCPEvaluate(k8sCPEnv{GTIDTag: true}, eff, cpLive(false)); !strings.Contains(cpClasses(f), "no gtid_mode") {
		t.Errorf("gtid_mode is required with the tag: %s", cpClasses(f))
	}
	if _, f := k8sCPEvaluate(k8sCPEnv{GTIDTag: false}, eff, cpLive(false)); len(f) != 0 {
		t.Errorf("gtid_mode is not required without the tag: %s", cpClasses(f))
	}
	// MariaDB has no gtid_mode: the MySQL specs are not applied, and its own semantic is optional here
	for _, s := range k8sCPApplicable(k8sCPEnv{Maria: true}) {
		if s.Option == "gtid_mode" || s.Option == "enforce_gtid_consistency" {
			t.Errorf("MariaDB must not be compared on %s", s.Option)
		}
	}
	for _, s := range k8sCPApplicable(k8sCPEnv{}) {
		if s.Option == "gtid_strict_mode" {
			t.Error("MySQL must not be compared on gtid_strict_mode")
		}
	}
	if names := k8sCPVariableNames(k8sCPEnv{Maria: true}); !slices.Contains(names, "log_bin_basename") || slices.Contains(names, "gtid_mode") {
		t.Errorf("variables to read on MariaDB: %v", names)
	}
}

