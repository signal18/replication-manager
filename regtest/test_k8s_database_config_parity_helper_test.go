// The observation script is run for real, in a local shell, on a fixture tree and a fake mountinfo: the
// script and its parser are tested together, as they run in the container.
func TestK8SCPObserveScriptAndParser(t *testing.T) {
	if _, err := exec.LookPath("sha256sum"); err != nil {
		t.Skip("no sha256sum on this host")
	}
	root := t.TempDir()
	files := cpFiles("2026-11-17T01:00:00Z")
	// a different stamp on disk than in the generated tree: the hash must not see it
	for i := range files {
		if files[i].name == "etc/mysql/my.cnf" {
			files[i].body = strings.ReplaceAll(files[i].body, "01:00:00", "09:09:09")
		}
	}
	for _, f := range files {
		p := filepath.Join(root, strings.Replace(f.name, "init/", "docker-entrypoint-initdb.d/", 1))
		if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
			t.Fatal(err)
		}
		if f.link != "" {
			if err := os.Symlink(f.link, p); err != nil {
				t.Fatal(err)
			}
		} else if err := os.WriteFile(p, []byte(f.body), 0644); err != nil {
			t.Fatal(err)
		}
	}
	// extras an operator may add, and a dangling link
	os.WriteFile(filepath.Join(root, "etc/mysql/custom.d/09_operator.cnf"), []byte("[mysqld]\n"), 0644)
	os.WriteFile(filepath.Join(root, "docker-entrypoint-initdb.d/replication-manager-cli"), []byte("bin"), 0755)
	mountinfo := filepath.Join(root, "mountinfo")
	mi := func(extra string) {
		os.WriteFile(mountinfo, []byte(
			"1 0 8:1 / / rw - ext4 /dev/x rw\n"+
				"2 1 8:1 /pvc-1/data /var/lib/mysql rw - ext4 /dev/x rw\n"+
				"3 1 8:1 /pvc-1/etc/mysql "+root+"/etc/mysql rw - ext4 /dev/x rw\n"+
				"4 1 8:1 /pvc-1/init "+root+"/docker-entrypoint-initdb.d rw - ext4 /dev/x rw\n"+extra), 0644)
	}
	mi("")
	script := strings.NewReplacer("/etc/mysql", root+"/etc/mysql", "/docker-entrypoint-initdb.d", root+"/docker-entrypoint-initdb.d", "/proc/self/mountinfo", mountinfo, "/var/lib/mysql", "/var/lib/mysql").Replace(k8sCPObserveScript)
	run := func() *k8sCPObserved {
		out, err := exec.Command("sh", "-c", script).CombinedOutput()
		if err != nil {
			t.Fatalf("the script failed: %v\n%s", err, out)
		}
		o, err := k8sCPParseObserved(string(out))
		if err != nil {
			t.Fatalf("%v\n%s", err, out)
		}
		return o
	}
	o := run()
	if !o.MyCnfOK || o.ConfdCount != 4 {
		t.Fatalf("my.cnf or conf.d: %+v", o)
	}
	// the local paths carry the temporary root, so the tree names are checked on the suffix
	var names []string
	for n := range o.Files {
		names = append(names, n)
	}
	for _, want := range []string{"/etc/mysql/my.cnf", "/etc/mysql/conf.d/01_default_network.cnf", "/etc/mysql/custom.d/09_operator.cnf", "/docker-entrypoint-initdb.d/replication-manager-cli"} {
		found := false
		for _, n := range names {
			if strings.HasSuffix(n, want) {
				found = true
			}
		}
		if !found {
			t.Errorf("the script did not list %s: %v", want, names)
		}
	}
	// the hash the script prints is the hash the test computes, for every generated file: a file without a
	// trailing newline (the generator writes some), the stamp on a line of its own, links to fragments
	tree := cpTree(t, files)
	compared := 0
	for _, n := range tree.Names("") {
		body, ok := tree.Resolve(n)
		if !ok {
			continue
		}
		local := root + "/" + strings.Replace(n, "init/", "docker-entrypoint-initdb.d/", 1)
		if got, present := o.Files[local]; present {
			compared++
			if got != k8sCPNormHash(body) {
				t.Errorf("%s: the script says %s, the test computes %s", n, got, k8sCPNormHash(body))
			}
		}
	}
	if compared < 8 {
		t.Errorf("only %d generated files were compared with the script's hash", compared)
	}
	if o.Mounts["etc"] != "/pvc-1/etc/mysql" || o.Mounts["init"] != "/pvc-1/init" || o.Mounts["confd"] != "" {
		t.Errorf("mount roots: %v", o.Mounts)
	}
}

func cpObserved(files map[string]string) *k8sCPObserved {
	return &k8sCPObserved{
		Mounts:  map[string]string{"etc": "/pvc-1/etc/mysql", "data": "/pvc-1/data", "init": "/pvc-1/init"},
		MyCnfOK: true, ConfdCount: 4, Files: files, Complete: true,
	}
}

func cpGoodFiles(t *testing.T, tree *k8sCPTree) map[string]string {
	t.Helper()
	files := map[string]string{}
	for _, n := range tree.Names("") {
		if body, ok := tree.Resolve(n); ok && (strings.HasPrefix(n, "etc/mysql/") || strings.HasPrefix(n, "init/")) {
			files[n] = k8sCPNormHash(body)
		}
	}
	return files
}

func TestK8SCPObservedMountProblems(t *testing.T) {
	if p := k8sCPObservedMountProblems(cpObserved(nil), true); len(p) != 0 {
		t.Fatalf("a good container: %v", p)
	}
	// whatever root the storage driver reports, the paths are mount points: nothing reads the root
	for _, root := range []string{"/pvc-1/data", "/", "/export/x/anything", "/var/lib/kubelet/pods/u/volume-subpaths/data/db1/0"} {
		o := cpObserved(nil)
		o.Mounts["data"], o.Mounts["etc"], o.Mounts["init"] = root, root, root
		if p := k8sCPObservedMountProblems(o, true); len(p) != 0 {
			t.Errorf("the driver reports %q: %v", root, p)
		}
	}
	for name, c := range map[string]struct {
		f    func(o *k8sCPObserved)
		want string
	}{
		"a legacy conf.d mount": {func(o *k8sCPObserved) { o.Mounts["confd"] = "/pvc-1/.system/conf.d" }, "legacy layout"},
		"no etc/mysql mount":    {func(o *k8sCPObserved) { o.Mounts["etc"] = "" }, "no mount at the etc path"},
		"no data mount":         {func(o *k8sCPObserved) { delete(o.Mounts, "data") }, "no mount at the data path"},
		"no init mount":         {func(o *k8sCPObserved) { o.Mounts["init"] = "" }, "no mount at the init path"},
	} {
		o := cpObserved(nil)
		c.f(o)
		if p := strings.Join(k8sCPObservedMountProblems(o, true), "; "); !strings.Contains(p, c.want) {
			t.Errorf("%s: %q", name, p)
		}
	}
	// the database container has no init mount
	o := cpObserved(nil)
	delete(o.Mounts, "init")
	if p := k8sCPObservedMountProblems(o, false); len(p) != 0 {
		t.Errorf("the database container without init: %v", p)
	}
	if p := k8sCPObservedMountProblems(o, true); len(p) == 0 {
		t.Error("a container that must mount init and does not is a problem")
	}
}

func TestK8SCPTreeProblems(t *testing.T) {
	tree := cpTree(t, cpFiles("t"))
	good := cpGoodFiles(t, tree)
	if len(good) == 0 {
		t.Fatal("no generated file to compare")
	}
	if p := k8sCPTreeProblems(cpObserved(good), tree, nil, true); len(p) != 0 {
		t.Fatalf("a good container: %v", p)
	}
	extra := map[string]string{"etc/mysql/custom.d/09_operator.cnf": "x", "init/replication-manager-cli": "-"}
	for k, v := range good {
		extra[k] = v
	}
	if p := k8sCPTreeProblems(cpObserved(extra), tree, nil, true); len(p) != 0 {
		t.Errorf("operator files are allowed: %v", p)
	}
	bad := func(f func(o *k8sCPObserved)) string {
		files := map[string]string{}
		for k, v := range good {
			files[k] = v
		}
		o := cpObserved(files)
		f(o)
		return strings.Join(k8sCPTreeProblems(o, tree, nil, true), "; ")
	}
	for name, c := range map[string]struct {
		f    func(o *k8sCPObserved)
		want string
	}{
		"empty my.cnf":   {func(o *k8sCPObserved) { o.MyCnfOK = false }, "my.cnf is missing or empty"},
		"empty conf.d":   {func(o *k8sCPObserved) { o.ConfdCount = 0 }, "conf.d is empty"},
		"dangling link":  {func(o *k8sCPObserved) { o.Dangling = []string{"/etc/mysql/conf.d/x.cnf"} }, "dangling"},
		"a missing file": {func(o *k8sCPObserved) { delete(o.Files, "etc/mysql/conf.d/01_default_network.cnf") }, "1 generated file(s) are not in the container: etc/mysql/conf.d/01_default_network.cnf"},
		"a changed file": {func(o *k8sCPObserved) { o.Files["etc/mysql/replication-manager.d/default_network.cnf"] = "deadbeef" }, "differ"},
		"a missing init": {func(o *k8sCPObserved) { delete(o.Files, "init/dbjobs_new") }, "init/dbjobs_new"},
	} {
		if got := bad(c.f); !strings.Contains(got, c.want) {
			t.Errorf("%s: %q", name, got)
		}
	}
	// the database container does not see init: its files are neither required nor compared there
	noInit := map[string]string{}
	for k, v := range good {
		if !strings.HasPrefix(k, "init/") {
			noInit[k] = v
		}
	}
	if p := k8sCPTreeProblems(cpObserved(noInit), tree, nil, false); len(p) != 0 {
		t.Errorf("the database container without init: %v", p)
	}
	if p := k8sCPTreeProblems(cpObserved(noInit), tree, nil, true); len(p) == 0 {
		t.Error("a container that must see init and does not is a problem")
	}
	// a volatile file is checked for presence only
	files := map[string]string{}
	for k, v := range good {
		files[k] = v
	}
	files["init/dbjobs_new"] = "other"
	if p := k8sCPTreeProblems(cpObserved(files), tree, map[string]bool{"init/dbjobs_new": true}, true); len(p) != 0 {
		t.Errorf("a volatile file differs: %v", p)
	}
}

