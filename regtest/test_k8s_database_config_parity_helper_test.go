func cpPodSpec(claim string) apiv1.PodSpec {
	mounts := []apiv1.VolumeMount{
		{Name: "data", MountPath: "/var/lib/mysql", SubPath: "data"},
		{Name: "data", MountPath: "/etc/mysql", SubPath: "etc/mysql"},
		{Name: "data", MountPath: "/docker-entrypoint-initdb.d", SubPath: "init"},
	}
	return apiv1.PodSpec{
		Volumes:        []apiv1.Volume{{Name: "data", VolumeSource: apiv1.VolumeSource{PersistentVolumeClaim: &apiv1.PersistentVolumeClaimVolumeSource{ClaimName: claim}}}},
		InitContainers: []apiv1.Container{{Name: "db1-init", VolumeMounts: slices.Clone(mounts)}},
		Containers: []apiv1.Container{
			{Name: "db1", VolumeMounts: slices.Clone(mounts[:2])}, // the database sees data and etc/mysql, not init
			{Name: "db1-dbjobs", VolumeMounts: slices.Clone(mounts)},
		},
	}
}

func TestK8SCPMountProblems(t *testing.T) {
	if p := k8sCPMountProblems(cpPodSpec("c1"), "db1", "c1"); len(p) != 0 {
		t.Fatalf("the contract spec has problems: %v", p)
	}
	// the database container is not required to mount init, and mounting it is not a problem either
	withInit := cpPodSpec("c1")
	withInit.Containers[0].VolumeMounts = append(withInit.Containers[0].VolumeMounts, apiv1.VolumeMount{Name: "data", MountPath: "/docker-entrypoint-initdb.d", SubPath: "init"})
	if p := k8sCPMountProblems(withInit, "db1", "c1"); len(p) != 0 {
		t.Errorf("an extra init mount in the database container is outside the contract but harmless: %v", p)
	}
	mutate := func(f func(s *apiv1.PodSpec)) []string {
		s := cpPodSpec("c1")
		f(&s)
		return k8sCPMountProblems(s, "db1", "c1")
	}
	for name, c := range map[string]struct {
		f    func(s *apiv1.PodSpec)
		want string
	}{
		"legacy conf.d mount in the database container": {func(s *apiv1.PodSpec) {
			s.Containers[0].VolumeMounts = []apiv1.VolumeMount{
				{Name: "data", MountPath: "/var/lib/mysql"},
				{Name: "data", MountPath: "/etc/mysql/conf.d", SubPath: ".system/conf.d"},
			}
		}, "legacy mount"},
		"dbjobs without /etc/mysql": {func(s *apiv1.PodSpec) {
			s.Containers[1].VolumeMounts = s.Containers[1].VolumeMounts[:1]
			s.Containers[1].VolumeMounts = append(s.Containers[1].VolumeMounts, apiv1.VolumeMount{Name: "data", MountPath: "/docker-entrypoint-initdb.d", SubPath: "init"})
		}, "dbjobs container does not mount /etc/mysql"},
		"wrong subPath": {func(s *apiv1.PodSpec) { s.InitContainers[0].VolumeMounts[1].SubPath = "conf" }, `from subPath "conf", expected "etc/mysql"`},
		"another claim": {func(s *apiv1.PodSpec) { s.Volumes[0].PersistentVolumeClaim.ClaimName = "other" }, "not the data claim"},
		"no init":       {func(s *apiv1.PodSpec) { s.InitContainers = nil }, "init container db1-init is not in the Pod spec"},
		"no dbjobs":     {func(s *apiv1.PodSpec) { s.Containers = s.Containers[:1] }, "dbjobs container db1-dbjobs is not in the Pod spec"},
		"mounted twice": {func(s *apiv1.PodSpec) {
			s.Containers[0].VolumeMounts = append(s.Containers[0].VolumeMounts, s.Containers[0].VolumeMounts[1])
		}, "2 times"},
		"not a PVC volume": {func(s *apiv1.PodSpec) { s.Volumes[0] = apiv1.Volume{Name: "data"} }, "not the data claim"},
	} {
		if p := strings.Join(mutate(c.f), "; "); !strings.Contains(p, c.want) {
			t.Errorf("%s: problems %q do not contain %q", name, p, c.want)
		}
	}
}

