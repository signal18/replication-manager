// testCDCFeedPostgres: a CDC feed into this MariaDB cluster from a PostgreSQL cluster of the
// same replication-manager (CDC_SOURCES.md), driven through the API settings only. The source
// cluster is REPMAN_REGTEST_CDC_SOURCE_CLUSTER, its database REPMAN_REGTEST_CDC_SOURCE_DATABASE
// (postgres when unset); the capture plugin (replplugin-postgresql) is installed. It checks:
//  1. the initial load of a table of varied types (bigint identity, numeric, timestamptz, jsonb,
//     an array, uuid, bytea, an enum, boolean, text), its rows equal on MariaDB;
//  2. inserts, updates (one of the key), deletes on PostgreSQL, equal on MariaDB;
//  3. the feed switched off, rows written on PostgreSQL, switched on again: the catch-up from
//     the slot;
//  4. the slot's retained WAL reported (CINF0040's numbers in the status), the slot the feed's;
//  5. at the end: the feed switched off, its slot and publication dropped through the API, the
//     test tables dropped on both sides.
//
// Not in the ALL list: it needs a PostgreSQL cluster. Run it by name:
// /api/clusters/<mariadb cluster>/tests/actions/run/testCDCFeedPostgres

const (
	cdcPgSchema = "regtest_cdc_pg"
	cdcPgTable  = "items"
	cdcPgPlugin = "postgresql"
)

// cdcPgRow is the comparable text of a row, the same on both sides.
const cdcPgSourceRows = `SELECT id::text || '|' || amount::text || '|' || to_char(created AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US') || '|' ||
 coalesce(doc::text, 'NULL') || '|' || coalesce(array_to_json(tags)::text, 'NULL') || '|' || uid::text || '|' || encode(payload, 'hex') || '|' ||
 mood::text || '|' || (CASE WHEN flag THEN '1' ELSE '0' END) || '|' || coalesce(note, 'NULL') FROM ` + cdcPgSchema + `.` + cdcPgTable + ` ORDER BY id`

const cdcPgTargetRows = "SELECT CONCAT_WS('|', id, amount, DATE_FORMAT(created, '%Y-%m-%d %H:%i:%s.%f'), IFNULL(doc, 'NULL'), IFNULL(tags, 'NULL'), uid, LOWER(HEX(payload)), mood, flag, IFNULL(note, 'NULL')) FROM " + cdcPgSchema + "." + cdcPgTable + " ORDER BY id"

func (regtest *RegTest) TestCDCFeedPostgres(cl *cluster.Cluster, conf string, test *cluster.Test) bool {
	const name = "CDCFeedPostgres"
	fail := func(format string, args ...any) bool {
		tlsLogf(cl, "FAIL "+name+": "+format, args...)
		return false
	}
	step := func(format string, args ...any) { tlsLogf(cl, name+": "+format, args...) }
	master := cl.GetMaster()
	srcName := strings.TrimSpace(os.Getenv("REPMAN_REGTEST_CDC_SOURCE_CLUSTER"))
	if master == nil || !master.IsMariaDB() || srcName == "" {
		tlsLogf(cl, "Skipping %s: needs a MariaDB master and REPMAN_REGTEST_CDC_SOURCE_CLUSTER", name)
		return true
	}
	if APIToken == nil || APIRequest == nil {
		tlsLogf(cl, "Skipping %s: no API in this run", name)
		return true
	}
	src, err := cl.GetClusterFromName(srcName)
	if err != nil || src.GetMaster() == nil || !src.GetMaster().IsPostgreSQLHost() {
		return fail("the source cluster %s has no PostgreSQL master: %v", srcName, err)
	}
	db := strings.TrimSpace(os.Getenv("REPMAN_REGTEST_CDC_SOURCE_DATABASE"))
	if db == "" {
		db = "postgres"
	}
	pg := src.GetMaster()
	pgExec := func(stmts ...string) error {
		for _, q := range stmts {
			if _, err := pg.Conn.Exec(q); err != nil {
				return fmt.Errorf("%s: %w", q, err)
			}
		}
		return nil
	}
	tok, err := APIToken(cl, config.GrantClusterSettings)
	if err != nil {
		return fail("%s", err)
	}
	base := "/api/clusters/" + cl.Name
	set := func(k, v string) error {
		code, _, resp, err := APIRequest(tok, http.MethodGet, base+"/settings/actions/set/"+k+"/"+url.PathEscape(v))
		if err != nil || code != 200 {
			return fmt.Errorf("%s=%s: HTTP %d %v %s", k, v, code, err, resp)
		}
		return nil
	}

	// the source table
	if err := pgExec(
		"DROP SCHEMA IF EXISTS "+cdcPgSchema+" CASCADE",
		"DROP TYPE IF EXISTS regtest_cdc_mood",
		"CREATE TYPE regtest_cdc_mood AS ENUM ('sad', 'ok', 'happy')",
		"CREATE SCHEMA "+cdcPgSchema,
		"CREATE TABLE "+cdcPgSchema+"."+cdcPgTable+` (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric(12,2) NOT NULL,
			created timestamptz NOT NULL, doc jsonb, tags text[], uid uuid NOT NULL, payload bytea NOT NULL, mood regtest_cdc_mood NOT NULL,
			flag boolean NOT NULL, note text)`,
		"INSERT INTO "+cdcPgSchema+"."+cdcPgTable+` (amount, created, doc, tags, uid, payload, mood, flag, note)
			SELECT g * 1.25, timestamptz '2026-11-27 10:00:00+01' + g * interval '1 minute', jsonb_build_object('n', g, 'tag', 'x' || g),
			ARRAY['a' || g, 'b "q"', NULL], md5(g::text)::uuid, decode(lpad(to_hex(g), 4, '0'), 'hex'),
			(ARRAY['sad','ok','happy'])[1 + g % 3]::regtest_cdc_mood, g % 2 = 0, CASE WHEN g % 5 = 0 THEN NULL ELSE 'note ' || g END
			FROM generate_series(1, 200) g`,
	); err != nil {
		return fail("the source table: %s", err)
	}
	defer pgExec("DROP SCHEMA IF EXISTS "+cdcPgSchema+" CASCADE", "DROP TYPE IF EXISTS regtest_cdc_mood")
	defer tlsExecOneConn(cl.GetMaster(), "DROP DATABASE IF EXISTS "+cdcPgSchema)

	// the feed, through the settings; at the end switched off, its slot and publication dropped
	for _, kv := range [][2]string{{"replication-plugin-feed-database", db}, {"replication-plugin-feed-tables", cdcPgSchema + "." + cdcPgTable}, {"replication-plugin-checkpoint-interval", "2"}} {
		if err := set(kv[0], kv[1]); err != nil {
			return fail("%s", err)
		}
	}
	if !cl.Conf.ReplicationPluginFeedCreateSourceObjects {
		if code, _, resp, err := APIRequest(tok, http.MethodGet, base+"/settings/actions/switch/replication-plugin-feed-create-source-objects"); err != nil || code != 200 {
			return fail("switch create-source-objects: HTTP %d %v %s", code, err, resp)
		}
	}
	if !cl.Conf.ReplicationPluginFeedEnabled {
		cl.Conf.ReplicationPluginFeedEnabled = true
	}
	if err := set("replication-plugin-feed-source-cluster", srcName); err != nil {
		return fail("%s", err)
	}
	defer func() {
		cl.Conf.ReplicationPluginFeedEnabled = false
		tlsWait(time.Minute, func() error {
			if _, running := cl.ReplicationPluginStatuses()[cdcPgPlugin]; running {
				return fmt.Errorf("running")
			}
			return nil
		})
		if ran, err := cl.DropReplicationFeedSourceObjects(cdcPgPlugin); err != nil {
			tlsLogf(cl, "%s: the slot and publication not dropped: %s (%v)", name, err, ran)
		} else {
			step("dropped on the source: %s", strings.Join(ran, "; "))
		}
		cl.Conf.ReplicationPluginFeedSourceCluster = ""
		cl.Conf.ReplicationPluginFeedEnabled = true
		cl.Conf.ReplicationPluginFeedCreateSourceObjects = false
	}()

	tdb := cl.GetMaster().Conn.DB
	same := func(what string, timeout time.Duration) error {
		return tlsWait(timeout, func() error {
			want, err := cdcPgRowsOf(pg.Conn.DB, cdcPgSourceRows)
			if err != nil {
				return err
			}
			have, err := cdcPgRowsOf(tdb, cdcPgTargetRows)
			if err != nil {
				return fmt.Errorf("%s: %w (status %v)", what, err, cl.ReplicationPluginStatuses()[cdcPgPlugin])
			}
			if len(want) != len(have) {
				return fmt.Errorf("%s: %d rows on PostgreSQL, %d on MariaDB (status %+v)", what, len(want), len(have), cl.ReplicationPluginStatuses()[cdcPgPlugin])
			}
			for i := range want {
				if want[i] != have[i] {
					return fmt.Errorf("%s: row %d differs:\n PostgreSQL %s\n MariaDB    %s", what, i, want[i], have[i])
				}
			}
			return nil
		})
	}

	// 1. the initial load
	start := time.Now()
	if err := same("initial load", 5*time.Minute); err != nil {
		return fail("%s", err)
	}
	step("initial load of 200 rows equal on MariaDB after %s", time.Since(start).Round(time.Second))

	// 2. changes
	if err := pgExec(
		"INSERT INTO "+cdcPgSchema+"."+cdcPgTable+" (amount, created, doc, tags, uid, payload, mood, flag, note) VALUES (9999.99, now(), '{\"new\": true}', '{}', gen_random_uuid(), '\\x00ff', 'happy', true, 'tab\there')",
		"UPDATE "+cdcPgSchema+"."+cdcPgTable+" SET amount = amount + 1, doc = doc || '{\"u\": 1}', note = 'line1\nline2' WHERE id % 10 = 0",
		"UPDATE "+cdcPgSchema+"."+cdcPgTable+" SET id = 100000 WHERE id = 7",
		"DELETE FROM "+cdcPgSchema+"."+cdcPgTable+" WHERE id % 17 = 0",
	); err != nil {
		return fail("changes: %s", err)
	}
	start = time.Now()
	if err := same("changes", 2*time.Minute); err != nil {
		return fail("%s", err)
	}
	step("inserts, updates (one of the key) and deletes equal on MariaDB after %s", time.Since(start).Round(time.Second))

	// 3. stopped, written, started: the catch-up from the slot
	switchFeed := func() error {
		code, _, resp, err := APIRequest(tok, http.MethodGet, base+"/settings/actions/switch/replication-plugin-feed-enabled")
		if err != nil || code != 200 {
			return fmt.Errorf("switch replication-plugin-feed-enabled: HTTP %d %v %s", code, err, resp)
		}
		return nil
	}
	if err := switchFeed(); err != nil {
		return fail("%s", err)
	}
	if err := tlsWait(time.Minute, func() error {
		if _, running := cl.ReplicationPluginStatuses()[cdcPgPlugin]; running {
			return fmt.Errorf("the feed still runs")
		}
		return nil
	}); err != nil {
		return fail("switch off: %s", err)
	}
	if err := pgExec("INSERT INTO "+cdcPgSchema+"."+cdcPgTable+" (amount, created, uid, payload, mood, flag) SELECT g, now(), gen_random_uuid(), '\\x01', 'ok', false FROM generate_series(1, 50) g",
		"UPDATE "+cdcPgSchema+"."+cdcPgTable+" SET flag = NOT flag WHERE id < 20"); err != nil {
		return fail("writes while stopped: %s", err)
	}
	var retained int64
	if err := pg.Conn.QueryRow("SELECT coalesce(pg_wal_lsn_diff(pg_current_wal_lsn(), restart_lsn), 0)::bigint FROM pg_replication_slots WHERE slot_name = $1", cluster.FeedObjectName(cl.Name)).Scan(&retained); err != nil {
		return fail("the feed's slot on the source: %s", err)
	}
	step("feed stopped, 50 inserts and 19 updates on PostgreSQL; the slot keeps %d bytes of WAL", retained)
	if err := switchFeed(); err != nil {
		return fail("%s", err)
	}
	start = time.Now()
	if err := same("catch-up", 3*time.Minute); err != nil {
		return fail("%s", err)
	}
	step("catch-up from the slot equal on MariaDB after %s", time.Since(start).Round(time.Second))

	// 4. the slot's retained WAL in the status
	if err := tlsWait(2*time.Minute, func() error {
		st, ok := cl.ReplicationPluginStatuses()[cdcPgPlugin]
		if !ok || st.SourceKind != "postgresql" || st.SourceRetainedMaxMB == 0 {
			return fmt.Errorf("no source numbers in the status: %+v", st)
		}
		return nil
	}); err != nil {
		return fail("%s", err)
	}
	st := cl.ReplicationPluginStatuses()[cdcPgPlugin]
	step("status: position %s applied %s, lag %d s, the slot keeps %d MB of %d MB; source warning %q", st.GTID, st.AppliedGTID, st.LagSeconds, st.SourceRetainedMB, st.SourceRetainedMaxMB, st.SourceWarning)
	return true
}

func cdcPgRowsOf(db *sql.DB, q string) ([]string, error) {
	rows, err := db.Query(q)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var s string
		if err := rows.Scan(&s); err != nil {
			return nil, err
		}
		out = append(out, s)
	}
	return out, rows.Err()
}
